import uuid
from decimal import Decimal
from django.db import models
from django.utils import timezone


class Customer(models.Model):
    """A customer who transacts with the shopkeeper on credit / cash."""

    name = models.CharField(max_length=150, db_index=True)
    phone = models.CharField(max_length=20, blank=True, default="")
    created_at = models.DateTimeField(default=timezone.now)

    class Meta:
        ordering = ["name"]
        verbose_name = "Customer"
        verbose_name_plural = "Customers"

    def __str__(self) -> str:
        if self.phone:
            return f"{self.name} ({self.phone})"
        return self.name


class EntryKind(models.TextChoices):
    CREDIT_GIVEN = "credit_given", "Credit Given (Udhaar)"
    PAYMENT_RECEIVED = "payment_received", "Payment Received (Varavu)"


class LedgerEntry(models.Model):
    """An individual credit or payment transaction recorded in the ledger."""

    customer = models.ForeignKey(
        Customer,
        on_delete=models.CASCADE,
        related_name="entries",
    )
    kind = models.CharField(
        max_length=30,
        choices=EntryKind.choices,
        db_index=True,
    )
    amount = models.DecimalField(
        max_digits=10,
        decimal_places=2,
    )
    note = models.TextField(blank=True, default="")
    source_text = models.TextField(blank=True, default="")
    created_at = models.DateTimeField(default=timezone.now, db_index=True)

    class Meta:
        ordering = ["-created_at", "-id"]
        verbose_name = "Ledger Entry"
        verbose_name_plural = "Ledger Entries"

    def __str__(self) -> str:
        return f"{self.customer.name} - {self.get_kind_display()}: ₹{self.amount}"


class DraftStatus(models.TextChoices):
    PENDING = "pending", "Pending Confirmation"
    CONFIRMED = "confirmed", "Confirmed & Saved"
    REJECTED = "rejected", "Rejected"


class SourceLabel(models.TextChoices):
    LIVE = "live", "Live Meta AI"
    MOCK = "mock", "Mock Engine"
    FALLBACK = "fallback", "Fallback Rules"


class DraftEntry(models.Model):
    """A proposed ledger entry generated by Meta AI or fallback rules, awaiting owner confirmation."""

    source_text = models.TextField()
    customer_name = models.CharField(max_length=150)
    matched_customer = models.ForeignKey(
        Customer,
        null=True,
        blank=True,
        on_delete=models.SET_NULL,
        related_name="drafts",
    )
    kind = models.CharField(
        max_length=30,
        choices=EntryKind.choices,
    )
    amount = models.DecimalField(
        max_digits=10,
        decimal_places=2,
    )
    note = models.TextField(blank=True, default="")
    status = models.CharField(
        max_length=20,
        choices=DraftStatus.choices,
        default=DraftStatus.PENDING,
        db_index=True,
    )
    source_label = models.CharField(
        max_length=20,
        choices=SourceLabel.choices,
        default=SourceLabel.MOCK,
    )
    batch_id = models.UUIDField(default=uuid.uuid4, db_index=True)
    created_at = models.DateTimeField(default=timezone.now)
    decided_at = models.DateTimeField(null=True, blank=True)

    class Meta:
        ordering = ["-created_at", "-id"]
        verbose_name = "Draft Entry"
        verbose_name_plural = "Draft Entries"

    def __str__(self) -> str:
        return (
            f"Draft [{self.status}]: {self.customer_name} - "
            f"{self.get_kind_display()} ₹{self.amount} ({self.source_label})"
        )
